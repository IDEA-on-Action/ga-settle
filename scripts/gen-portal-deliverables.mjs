#!/usr/bin/env node
// F-070: docs/deliverables/README.md 대장 → apps/api/src/portal-deliverables.gen.ts 생성.
// 사용: node scripts/gen-portal-deliverables.mjs        (생성)
//       node scripts/gen-portal-deliverables.mjs --check (drift 검사, 불일치 시 exit 1)
import { readFileSync, writeFileSync, existsSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const registerPath = path.join(root, "docs/deliverables/README.md");
const outPath = path.join(root, "apps/api/src/portal-deliverables.gen.ts");

const readme = readFileSync(registerPath, "utf8");

// 대장 행: | 코드 | 문서명 | 파일 | 버전 | 상태 | 전달일 | 비고 |
const docs = [];
for (const line of readme.split("\n")) {
  const cells = line.split("|").map((s) => s.trim());
  if (cells.length < 8 || !/^GS-[A-Z]+-\d+$/.test(cells[1])) continue;
  const [, code, title, fileCell, version, status, delivered, note] = cells;
  const fileMatch = fileCell.match(/\(([^)]+\.md)\)/);
  const file = fileMatch ? fileMatch[1] : null;
  let content = null;
  if (file) {
    const p = path.join(root, "docs/deliverables", file);
    if (!existsSync(p)) {
      console.error(`대장 파일 누락: ${file} (대장 행 ${code})`);
      process.exit(1);
    }
    content = readFileSync(p, "utf8");
  }
  docs.push({
    code,
    title,
    file,
    version: version === "-" ? null : version,
    status,
    delivered: delivered === "-" ? null : delivered,
    note: note || null,
    content,
  });
}

if (docs.length === 0) {
  console.error("대장에서 GS-* 행을 찾지 못함 - README.md 테이블 형식 확인");
  process.exit(1);
}

const out = `// AUTO-GENERATED by scripts/gen-portal-deliverables.mjs - 직접 수정 금지 (F-070)
// SoT: docs/deliverables/README.md (대장) + 각 문서 마크다운. 갱신: node scripts/gen-portal-deliverables.mjs

export interface DeliverableDoc {
  code: string;
  title: string;
  file: string | null;
  version: string | null;
  status: string;
  delivered: string | null;
  note: string | null;
  /** 마크다운 정본. 인증된 다운로드 전용 - 공개 화면에 노출 금지 (계약 금액 등 민감정보 포함) */
  content: string | null;
}

export const DELIVERABLE_DOCS: DeliverableDoc[] = ${JSON.stringify(docs, null, 2)};
`;

if (process.argv.includes("--check")) {
  const current = existsSync(outPath) ? readFileSync(outPath, "utf8") : "";
  if (current !== out) {
    console.error("portal-deliverables drift: 대장/문서 변경이 gen 파일에 미반영 - node scripts/gen-portal-deliverables.mjs 실행 필요");
    process.exit(1);
  }
  console.log(`portal-deliverables: OK (${docs.length}건 동기)`);
} else {
  writeFileSync(outPath, out);
  console.log(`generated: ${path.relative(root, outPath)} (${docs.length}건)`);
}
